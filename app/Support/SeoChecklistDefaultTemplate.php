    public static function stageTitle(string $key): string
    {
        $stages = self::stages();
        if (isset($stages[$key]['title'])) {
            return $stages[$key]['title'];
        }

        return $key;
    }

    /**
     * Скелет этапов для пресета (без legacy-alias connect).
     *
     * @return list<array{key:string,title:string,lead:?string,sort:int}>
     */
    public static function skeletonStagesList(): array
    {
        $list = [];
        foreach (self::stages() as $key => $meta) {
            if ($key === 'connect') {
                continue;
            }
            $list[] = [
                'key' => $key,
                'title' => (string) $meta['title'],
                'lead' => isset($meta['lead']) ? (string) $meta['lead'] : null,
                'sort' => (int) $meta['sort'],
            ];
        }

        return $list;
    }

    /**
     * @param  list<array{key?:string,title?:string,lead?:?string,sort?:int}>  $list
     * @return array<string, array{title:string,lead:?string,sort:int}>
     */
    public static function stagesMapFromList(array $list): array
    {
        $map = [];
        foreach ($list as $row) {
            if (!is_array($row)) {
                continue;
            }
            $key = trim((string) ($row['key'] ?? ''));
            if ($key === '' || $key === 'connect') {
                continue;
            }
            $map[$key] = [
                'title' => trim((string) ($row['title'] ?? '')) !== ''
                    ? trim((string) $row['title'])
                    : $key,
                'lead' => isset($row['lead']) && trim((string) $row['lead']) !== ''
                    ? trim((string) $row['lead'])
                    : null,
                'sort' => (int) ($row['sort'] ?? 0),
            ];
        }

        return $map;
    }

    /**
     * @return array<string, array{title:string,lead:?string,sort:int}>
     */
    public static function skeletonStagesMap(): array
    {
        return self::stagesMapFromList(self::skeletonStagesList());
    }

    /**
     * @return array{title:string,sort:int,lead?:string}|null
     */
    public static function stageMeta(string $key): ?array
    {
        $stages = self::stages();

        return $stages[$key] ?? null;
    }

