    public static function repeatRuleKeys(): array
    {
        return array_merge(array_keys(self::repeatRuleLabels()), ['weekly']);
    }

    public static function repeatIntervalDays(?string $rule): ?int
    {
        $map = [
            'every_3' => 3,
            'every_5' => 5,
            'every_7' => 7,
            'every_15' => 15,
            'every_60' => 60,
            'every_90' => 90,
            'every_180' => 180,
            'every_365' => 365,
            'weekly' => 7,
        ];

        return $map[$rule] ?? null;
    }

    public static function normalizeRepeatRule($value): ?string
    {
        if ($value === null || $value === '') {
            return null;
        }
        $value = (string) $value;
        if (!in_array($value, self::repeatRuleKeys(), true)) {
            return null;
        }

        return $value;
    }

    public static function repeatRuleLabel(?string $rule): string
    {
        if ($rule === null || $rule === '') {
            return __('No repeat');
        }
        if ($rule === 'weekly') {
            return __('Every 7 days');
        }
        $labels = self::repeatRuleLabels();

        return $labels[$rule] ?? $rule;
    }
